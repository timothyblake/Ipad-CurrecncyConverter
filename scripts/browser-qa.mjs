import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const launch = process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {};
const browser = await chromium.launch({ headless: true, ...launch });
const context = await browser.newContext({viewport:{width:1194,height:834}});
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const baseURL = process.env.QA_URL ?? 'http://127.0.0.1:4387';
const response = {result:'success',base_code:'GBP',time_last_update_unix:Math.floor(Date.now()/1000),rates:{GBP:1,JMD:204.5,USD:1.31,EUR:1.18}};
await page.route('https://open.er-api.com/**',route=>route.fulfill({json:response}));
await page.goto(baseURL);
await page.getByText('Rates up to date',{exact:true}).waitFor();
assert.match(await page.locator('#converted-amount').innerText(),/4.89/);
for (const name of ['US Dollar', 'Euro', 'Jamaican Dollar']) {
  const card = page.getByRole('button', { name: `Use ${name} as input currency`, exact: true });
  await card.click();
  assert.equal(await card.getAttribute('aria-pressed'), 'true');
  assert.equal(await page.getByLabel(`Amount in ${name}`, { exact: true }).inputValue(), '1000');
}

await page.getByLabel('Select source currency').selectOption('USD');
assert.equal(await page.evaluate(() => sessionStorage.getItem('currency_input_currency')), 'USD');
await page.reload();
await page.getByLabel('Amount in US Dollar').waitFor();
await page.getByRole('button', { name: 'Switch conversion direction' }).click();
await page.reload();
await page.getByLabel('Amount in British Pound').waitFor();
await page.evaluate(() => sessionStorage.setItem('currency_input_currency', 'INVALID'));
await page.reload();
await page.getByLabel('Amount in Jamaican Dollar').waitFor();
await page.locator('#source-amount').fill('5000');
assert.match(await page.locator('#converted-amount').innerText(),/24.45/);
await page.getByLabel('Select source currency').selectOption('USD');
await page.getByLabel('Amount in US Dollar').fill('131');
assert.match(await page.locator('#converted-amount').innerText(),/100.00/);
await page.getByRole('button',{name:'Switch conversion direction'}).click();
await page.getByLabel('Amount in British Pound').fill('100');
assert.match(await page.locator('#converted-amount').innerText(),/131.00/);
await page.getByLabel('Select target currency').selectOption('EUR');
assert.match(await page.locator('#converted-amount').innerText(),/118.00/);
await page.getByLabel('Amount in British Pound').fill('1.2.3');
await page.getByRole('alert').waitFor();
assert.match(await page.locator('#converted-amount').innerText(),/—/);
await page.locator('#source-amount').fill('');
assert.match(await page.locator('#converted-amount').innerText(),/0.00/);
await page.getByRole('button',{name:'Switch conversion direction'}).click();
await page.getByLabel('Select source currency').selectOption('JMD');
await page.locator('#source-amount').fill('1000');
for (const [width,height] of [[1194,834],[1080,810],[834,1194],[810,1080],[390,844]]) {
  await page.setViewportSize({width,height});
  await page.screenshot({path:`/tmp/currency-${width}.png`,fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`Overflow at ${width}`);
  const controls = await page.locator('button,select,input').evaluateAll(elements=>elements.map(element=>({label:element.textContent,height:element.getBoundingClientRect().height})));
  assert.ok(controls.every(control=>control.height>=64),`Small control at ${width}`);
  await page.locator('#source-amount').fill('999999999.99');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`Long amount overflow at ${width}`);
  await page.locator('#source-amount').fill('1000');
}
await page.evaluate(()=>navigator.serviceWorker.ready);
await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
await context.setOffline(true);
await page.reload();
await page.getByText('Offline rates',{exact:true}).waitFor({timeout:10000}).catch(async error=>{console.log(await page.locator('body').innerText());console.log(errors);console.log(await page.evaluate(()=>({online:navigator.onLine,cache:localStorage.getItem('currency_rates_cache')})));throw error;});
assert.match(await page.locator('#converted-amount').innerText(),/4.89/);
await page.locator('#source-amount').fill('5000');
assert.match(await page.locator('#converted-amount').innerText(),/24.45/);
await context.setOffline(false);
await page.getByText('Rates up to date',{exact:true}).waitFor();
await page.route('https://open.er-api.com/**',route=>route.abort());
await page.getByRole('button',{name:'Refresh exchange rates'}).click();
await page.getByText('Saved rates',{exact:true}).waitFor();
assert.ok(errors.length===0,errors.join('\n'));
console.log('PASS: conversions, selections, switch, amount editing, validation, 5 viewports, 64px touch controls, large amounts, offline reload, reconnection, API failure, no browser errors.');
await context.close();
const fallbackContext=await browser.newContext();
const fallbackPage=await fallbackContext.newPage();
await fallbackPage.route('https://open.er-api.com/**',route=>route.abort());
await fallbackPage.goto(baseURL);
await fallbackPage.getByText('Estimated rates',{exact:true}).waitFor();
assert.match(await fallbackPage.locator('#converted-amount').innerText(),/4.89/);
console.log('PASS: first visit with unavailable API uses labelled example rates.');
await browser.close();
